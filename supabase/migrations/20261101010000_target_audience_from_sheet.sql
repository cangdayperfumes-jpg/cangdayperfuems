  FROM public.products p
  JOIN sheet s ON trim(p.name_en) = s.name
),
loose_sheet AS (
  SELECT lower(regexp_replace(trim(name), '[[:space:]]+', ' ', 'g')) AS k, min(audience) AS audience, count(DISTINCT audience) AS n
  FROM sheet
  GROUP BY 1
),
loose AS (
  SELECT p.id, l.audience
  FROM public.products p
  JOIN loose_sheet l ON lower(regexp_replace(trim(p.name_en), '[[:space:]]+', ' ', 'g')) = l.k
  WHERE l.n = 1 AND p.id NOT IN (SELECT id FROM exact)
),
target AS (
  SELECT id, audience FROM exact
  UNION ALL
  SELECT id, audience FROM loose
),
changed AS (
  UPDATE public.products p
  SET target_audience = t.audience
  FROM target t
  WHERE p.id = t.id
    AND p.target_audience IS DISTINCT FROM t.audience
  RETURNING p.name_en, p.target_audience
),
